-- Трасса задаётся не сеткой клеток, а осевой линией: список опорных
-- точек, через которые kart.lua проводит замкнутую кривую и красит по
-- ней дорогу, бордюр и обочину. Из той же кривой берутся путевые точки
-- для соперников, контрольные отметки для круга и место, куда Лакиту
-- возвращает вылетевших.
--
-- Поэтому трассу можно двигать точками, не перерисовывая клетки, а всё
-- остальное расставляется вдоль неё долей круга s (0..1) и смещением
-- вбок в тайлах (минус - левее осевой):
--
--   { "boxes", s, n }        n ящиков поперёк дороги

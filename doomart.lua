-- doomart - палитра, стенные текстуры, спрайты, оружие и карты для doom.lua.
--
-- Всё нарисовано шестнадцатеричными цифрами: цифра - индекс палитры,
-- точка - прозрачная точка (у стен прозрачных точек не бывает). Текстура
-- стены 16x16, монстры 16x24, предметы 12x12, оружие рисуется внизу
-- экрана как есть.
--
-- Палитра собрана цепочками: 1-2-3-4-5 серое, 6-7-8-9 коричневое,
-- a-b-c красное. Затемнение с расстоянием - это шаг назад по цепочке
-- (art.darker), поэтому "тёмный вариант" любой текстуры получается сам и
-- второго комплекта графики не требует.

local art = {}

art.palette = {
	[0]  = 0x000000,   -- обводка, пустота
	[1]  = 0x141414,   -- почти чёрный: дальний пол и потолок
	[2]  = 0x303030,   -- тёмно-серый
	[3]  = 0x5C5C5C,   -- серый: сталь
	[4]  = 0x909090,   -- светло-серый
	[5]  = 0xD0D0D0,   -- белый: блики, кость
	[6]  = 0x2A1A0E,   -- тёмно-коричневый
	[7]  = 0x5A3A1E,   -- коричневый: кирпич, шкура импа
	[8]  = 0x8A5A2E,   -- светло-коричневый
	[9]  = 0xC08A46,   -- песочный: кожа, блик на кирпиче
	[10] = 0x400C0C,   -- тёмно-красный: кровь
	[11] = 0x981818,   -- красный
	[12] = 0xF04018,   -- огонь
	[13] = 0xE8C040,   -- жёлтый: лампы, гильзы, ключ
	[14] = 0x2860D8,   -- синий: броня, ключ
	[15] = 0x30A030,   -- зелёный: аптечка, ключ
}

-- Шаг затемнения: цвет -> цвет на ступень темнее. Освещение считается

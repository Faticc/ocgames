-- marioart - палитра, тайлы, спрайты и карты уровней.
--
-- Всё нарисовано шестнадцатеричными цифрами: цифра - индекс палитры,
-- точка - прозрачная точка. Тайл фона 8x8, тайл мира равен одному тайлу
-- картинки, поэтому экран 160x100 - это 20x12 тайлов плюс две строки
-- под счёт.
--
-- Палитра одна на всю игру, а подземелье просто переопределяет три цвета
-- (небо и две краски кладки) - поэтому смена темы не стоит ни байта
-- лишней графики.

